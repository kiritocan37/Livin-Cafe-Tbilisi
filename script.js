let lang = localStorage.getItem('livin-lang') || 'en';

function setLang(l) {
  lang = l;
  localStorage.setItem('livin-lang', l);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (T[l][k] !== undefined) el.innerHTML = T[l][k];
  });
  document.querySelectorAll('.lang-btn').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === l)
  );
  document.documentElement.lang = l;
}

// Nav scroll
const nav = document.getElementById('nav');
window.addEventListener('scroll', () =>
  nav.classList.toggle('scrolled', scrollY > 60)
);

// Hamburger
const ham = document.getElementById('hamburger');
const mob = document.getElementById('mobileNav');
ham.addEventListener('click', () => {
  ham.classList.toggle('active');
  mob.classList.toggle('open');
  document.body.style.overflow = mob.classList.contains('open') ? 'hidden' : '';
});
function closeMobile() {
  ham.classList.remove('active');
  mob.classList.remove('open');
  document.body.style.overflow = '';
}

// Smooth scroll
document.querySelectorAll('a[href^="#"]').forEach(a => {
  a.addEventListener('click', e => {
    e.preventDefault();
    closeMobile();
    document.querySelector(a.getAttribute('href'))?.scrollIntoView({ behavior: 'smooth' });
  });
});

// Scroll reveal
const obs = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (e.isIntersecting) { e.target.classList.add('vis'); obs.unobserve(e.target); }
  });
}, { threshold: 0.08, rootMargin: '0px 0px -40px 0px' });
document.querySelectorAll('.reveal').forEach(el => obs.observe(el));

// Active nav link highlight
const sects = document.querySelectorAll('section[id]');
window.addEventListener('scroll', () => {
  const y = scrollY + 150;
  sects.forEach(s => {
    const link = document.querySelector(`.nav-center a[href="#${s.id}"]`);
    if (link) {
      link.style.color = (y >= s.offsetTop && y < s.offsetTop + s.offsetHeight)
        ? 'var(--green-glow)' : '';
    }
  });
});

// Menu tabs
document.querySelectorAll('.tab-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
    document.querySelectorAll('.menu-panel').forEach(p => p.classList.remove('active'));
    btn.classList.add('active');
    const panel = document.getElementById('tab-' + btn.dataset.tab);
    if (panel) panel.classList.add('active');
  });
});

// Gallery drag scroll
const strip = document.querySelector('.gallery-strip');
if (strip) {
  let isDown = false, startX, scrollLeft;
  strip.addEventListener('mousedown', e => {
    isDown = true; strip.classList.add('dragging');
    startX = e.pageX - strip.offsetLeft; scrollLeft = strip.scrollLeft;
  });
  strip.addEventListener('mouseleave', () => { isDown = false; strip.classList.remove('dragging'); });
  strip.addEventListener('mouseup', () => { isDown = false; strip.classList.remove('dragging'); });
  strip.addEventListener('mousemove', e => {
    if (!isDown) return;
    e.preventDefault();
    const x = e.pageX - strip.offsetLeft;
    strip.scrollLeft = scrollLeft - (x - startX) * 1.4;
  });
}

// Init
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach(b =>
    b.addEventListener('click', () => setLang(b.dataset.lang))
  );
  setLang(lang);
});
